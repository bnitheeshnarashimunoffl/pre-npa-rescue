"""Model cards rendered from ``metrics.json`` (task 2.5).

Headings follow IS/ISO/IEC TS 4213 (classification performance assessment) and
IS/ISO/IEC 25059:2023 (quality of AI systems): intended use, data, metrics with confidence
intervals, limitations, explainability, robustness, fairness (IS/ISO/IEC TR 24027:2021),
monitoring plan and owner. Cards are generated, never hand-edited, so they always match the
numbers in ``metrics.json``.
"""

from collections.abc import Mapping, Sequence
from typing import Any

from npa_models.fairness import MAX_GAP, MIN_GROUP_SIZE, MIN_RATIO

PENDING = "pending"
STANDARDS_NOTE = (
    "Design alignment with Indian Standards, not certification: IS/ISO/IEC TS 4213, "
    "IS/ISO/IEC 25059:2023, IS/ISO/IEC TR 24027:2021, IS/ISO/IEC 23053:2022, "
    "IS/ISO/IEC 42001:2023."
)


def _num(v: Any) -> str:
    if v is None:
        return "n/a"
    return f"{v:.3f}" if isinstance(v, float) else str(v)


def _ci(m: Mapping[str, Any], key: str) -> str:
    ci = m.get("ci95", {}).get(key)
    return f"{_num(m[key])} ({_num(ci[0])}–{_num(ci[1])})" if ci else _num(m.get(key))


def _kv(d: Mapping[str, Any]) -> str:
    return ", ".join(f"{k} {_num(v)}" for k, v in d.items())


def _table(header: Sequence[str], rows: Sequence[Sequence[str]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(lines)


def _header(title: str, metrics: Mapping[str, Any], version: str) -> str:
    d = metrics["data"]
    pending = (
        "\n> **Test months (2026-07..09): pending.** WS1's labels don't cover them yet, so the "
        "numbers below are on the validation months (2026-04..06), which also fitted the "
        "calibrator and are therefore slightly optimistic. Final numbers follow once WS1 "
        "extends the label horizon.\n"
        if d["test_status"] == PENDING
        else ""
    )
    return (
        f"# Model card: {title}\n\n"
        f"- **Model version:** `{version}`\n"
        f"- **As-of month:** {metrics['as_of_month']}\n"
        f"- **Evaluation window:** {d['evaluation_window']} (test status: {d['test_status']})\n"
        f"- **Seed:** {d['seed']}; 95% intervals from {d['bootstrap_resamples']} bootstrap "
        "resamples\n"
        f"- **Generated by:** `npa-models evaluate` from `metrics.json`; do not edit by hand.\n"
        f"{pending}"
    )


def _fairness(metrics: Mapping[str, Any], model: str) -> str:
    block = metrics["fairness"].get(model)
    if not block:
        return "## Fairness (IS/ISO/IEC TR 24027:2021)\n\nNot evaluated.\n"
    rows = []
    for attr, b in block.items():
        for key, value in b.items():
            if key.endswith(("_diff", "_ratio")):
                flagged = key in b["flagged"]
                rows.append([attr, f"`{key}`", _num(value), "**flagged**" if flagged else "ok"])
    flags = [f for f in metrics["fairness_flags"] if f["model"] == model]
    text = (
        "## Fairness (IS/ISO/IEC TR 24027:2021)\n\n"
        f"Population: {metrics['fairness_population'][model]}. Protected attributes are read "
        "only in `fairness.py`, after scoring; they are never model inputs. A `*_diff` is the "
        f"largest gap between groups (flagged above {MAX_GAP}); a `*_ratio` is the smallest "
        f"over the largest rate (four-fifths warning below {MIN_RATIO}). Groups with fewer than "
        f"{MIN_GROUP_SIZE} accounts are reported in `metrics.json` but left out of the gaps.\n\n"
        + _table(["Attribute", "Metric", "Value", "Status"], rows)
        + "\n"
    )
    if flags:
        text += "\n### Flagged gaps and mitigation\n\n" + "\n".join(
            f"- {f['attribute']} `{f['metric']}` = {_num(f['value'])} "
            f"({f['tier']}, threshold {f['threshold']}): {f['mitigation']}"
            for f in flags
        )
        text += "\n"
    else:
        text += "\nNo gap above the thresholds.\n"
    return text


def _monitoring(extra: str) -> str:
    return (
        "## Monitoring plan\n\n"
        "- Monthly, on each new as-of month: score distribution and band shares, population "
        "stability of the top features, and the metrics above once outcomes arrive.\n"
        "- Monthly fairness check with the same thresholds; any new flag goes to WS7 "
        "(`governance/`) and the model owner.\n"
        f"- {extra}\n"
        "- Retrain when ROC-AUC / macro-F1 drops by more than 0.03 or a fairness flag persists "
        "for two months; every output carries `model_version` (IS/ISO/IEC 42001:2023 "
        "inventory).\n"
    )


def _footer() -> str:
    owner = "WS2 (Analysis & classification models), `packages/models`."
    return f"## Owner\n\n{owner}\n\n{STANDARDS_NOTE}\n"


def early_warning_card(metrics: Mapping[str, Any]) -> str:
    ew = metrics["early_warning"]
    window = metrics["data"]["evaluation_window"]
    w = ew[window]
    rows = []
    for name in ("roll_forward", "npa_90d", "baseline"):
        m = w[name]
        if m == PENDING:
            rows.append([name, PENDING, PENDING, PENDING, PENDING, PENDING])
        else:
            rows.append(
                [
                    name,
                    _ci(m, "roc_auc"),
                    _ci(m, "pr_auc"),
                    _ci(m, "brier"),
                    _ci(m, "ks"),
                    _num(m["base_rate"]),
                ]
            )
    rob = ew["robustness"]
    shap = list(metrics["explainability"]["mean_abs_shap"].items())[:8]
    codes = metrics["explainability"]["reason_code_share_high_band"]
    return "\n".join(
        [
            _header("early warning (roll forward in 30–60 days)", metrics, ew["model_version"]),
            "## Intended use\n\nRank card accounts by the probability of rolling forward to "
            "the next delinquency bucket in 30–60 days, so the bank can offer help before "
            "NPA. It decides who is looked at first, never a penalty. Not for credit "
            "decisions, pricing or limit changes.\n",
            "## Data\n\nSynthetic monthly account features (WS1, `features.parquet`), "
            "time-based split: train ≤ 2026-03, validation 2026-04..06, test 2026-07..09. "
            f"Rows: {_kv(metrics['data']['rows'])}.\n",
            f"## Metrics ({window}, 95% CI)\n\n"
            + _table(["Head", "ROC-AUC", "PR-AUC", "Brier", "KS", "Base rate"], rows)
            + f"\n\nTargets: ROC-AUC ≥ 0.80, PR-AUC well above the base rate. Risk bands: high ≥ "
            f"{ew['thresholds']['high']}, medium ≥ {ew['thresholds']['medium']}. "
            f"Band shares: validation {_kv(ew['band_share']['validation'])}; "
            f"as-of month {_kv(ew['band_share']['as_of_month'])}. "
            f"Cut-off for a 6.5% high band: {_num(ew['suggested_high_threshold_6_5pct'])}.\n",
            "## Limitations\n\n- Trained on synthetic data; real-world performance is unknown.\n"
            "- Isotonic calibration on about three months of data gives a coarse step function.\n"
            "- `city` is excluded as a proxy for state/region; other proxies are checked through "
            "the fairness section, not removed.\n",
            "## Explainability\n\nLightGBM with monotonic constraints (risk never falls as "
            "arrears grow). Each score carries its top 3 plain-language reasons in en/ta/hi from "
            "TreeSHAP (`reason_codes.yaml`). Largest mean |SHAP| (log-odds):\n\n"
            + _table(["Feature", "Mean |SHAP|"], [[f"`{k}`", _num(v)] for k, v in shap])
            + "\n\nReason codes among high-band accounts: "
            + (_kv(codes) or "none")
            + ".\n",
            "## Robustness\n\n"
            + _table(
                ["Scenario", "ROC-AUC", "Change", "PR-AUC", "Brier"],
                [
                    [
                        k,
                        _num(v["roc_auc"]),
                        _num(v["roc_auc_change"]),
                        _num(v["pr_auc"]),
                        _num(v["brier"]),
                    ]
                    for k, v in rob.items()
                ],
            )
            + "\n",
            _fairness(metrics, "early_warning"),
            _monitoring("Calibration plot by month; refit the calibrator if Brier drifts."),
            _footer(),
        ]
    )


def segment_card(metrics: Mapping[str, Any]) -> str:
    seg = metrics["segment"]
    window = metrics["data"]["evaluation_window"]
    m = seg[window]
    if m == PENDING:
        body = "Pending.\n"
    else:
        labels = m["labels"]
        body = (
            f"Macro-F1 {_ci(m, 'macro_f1')}; rows relabelled by the conservative rule: "
            f"{_num(m['low_confidence_share'])}.\n\n"
            + _table(["Class", "Recall"], [[c, _num(m["recall"][c])] for c in labels])
            + "\n\nConfusion matrix (rows = truth, columns = prediction):\n\n"
            + _table(
                ["", *labels],
                [
                    [t, *(str(v) for v in row)]
                    for t, row in zip(labels, m["confusion_matrix"], strict=True)
                ],
            )
            + "\n"
        )
    return "\n".join(
        [
            _header("segmentation (forgot / can't pay / won't pay)", metrics, seg["model_version"]),
            "## Intended use\n\nSuggest the kind of conversation (reminder, hardship help or a "
            "firmer route) for an at-risk account. A suggestion for the collector and the "
            "rules engine, never an automatic action.\n",
            "## Data\n\nSame features and time split as the early-warning model; target "
            "`segment_truth` from WS1's simulator.\n",
            f"## Metrics ({window}, 95% CI)\n\n{body}",
            "## Limitations\n\n- `forgot` and `wont_pay` are hard to tell from `not_at_risk` on "
            "synthetic data; most errors are about *whether* the account rolls, not *why*.\n"
            "- `SegmentResult` has no field for the `low_confidence` flag; it is in "
            "`score_frame` only.\n",
            "## Explainability\n\nThe conservative rule: when `wont_pay` is the top class with "
            f"probability < {seg['rule']['wont_pay_min_confidence']}, the output is the "
            "lower-harm `cant_pay` with `low_confidence` (RBI fair-treatment principles).\n",
            "## Robustness\n\nNot measured separately; shares features with the early-warning "
            "model (see its card).\n",
            _fairness(metrics, "segment"),
            _monitoring("Share of `wont_pay` by month and by group; human review of firm cases."),
            _footer(),
        ]
    )


def uplift_card(metrics: Mapping[str, Any], strategies: Mapping[str, Any] | None) -> str:
    up = metrics["uplift"]
    if up == PENDING:
        return (
            "# Model card: uplift\n\nPending: no uplift model was trained "
            "(needs WS1's `experiment.parquet`).\n"
        )
    ev = up["evaluation_out_of_fold"]
    policy = "Pending: needs WS1's experiment potential outcomes and simulator.\n"
    if strategies is not None:
        rows = [
            [
                name,
                s["role"],
                _num(s["npa_rate"]),
                _num(s["cure_rate"]),
                f"₹{s['collection_cost_paise'] / 100:,.0f}",
                str(s["contacts_made"]),
            ]
            for name, s in strategies["strategies"].items()
        ]
        red = strategies["npa_reduction_pct"]
        policy = (
            _table(["Strategy", "Role", "NPA rate", "Cure rate", "Cost", "Contacts"], rows)
            + f"\n\nNPA reduction of ours vs call everyone: {_num(red['call_everyone'])}%; vs "
            f"risk-only targeting: {_num(red['risk_targeting'])}%. The oracle uses hidden truth "
            "and is an upper bound only, never our result.\n"
        )
    return "\n".join(
        [
            _header("uplift (who is worth contacting)", metrics, up["model_version"]),
            "## Intended use\n\nDecide whether contacting an at-risk customer helps at all, and "
            "which contact is worth its cost. Sleeping dogs and sure things get no contact "
            "(RBI RBC Directions para 454Z: no excessive contact).\n",
            "## Data\n\nWS1's randomised experiment (`experiment.parquet`, one month of "
            f"at-risk accounts, {ev['n']} rows) joined to features.\n",
            "## Metrics (out-of-fold, 3-fold cross-fitting)\n\n"
            f"Qini AUC {_num(ev['qini_auc'])}, uplift AUC {_num(ev['uplift_auc'])}, agreement "
            f"with the hidden group {_num(ev.get('group_accuracy'))}. Group shares: "
            f"{_kv(ev['group_share'])}.\n\n### Policy simulation\n\n{policy}",
            "## Limitations\n\n- One month of experiment data; individual uplift is mostly "
            "noise, so ranking (Qini) is weak and gains come from the behaviour context.\n"
            "- Sleeping dogs tend to be over-predicted on small experiments.\n"
            f"- The cure value (₹{up['cure_value_paise'] / 100:,.0f}) is an assumption.\n",
            "## Explainability\n\nT-learner: per-arm cure probabilities and their difference "
            "from no contact are stored with every score (`uplift_<arm>`, `p_control`).\n",
            "## Robustness\n\nCross-fitted estimates only; no in-sample evaluation.\n",
            _fairness(metrics, "uplift"),
            _monitoring("Re-run the randomised holdout each quarter to re-estimate uplift."),
            _footer(),
        ]
    )


def render_all(metrics: Mapping[str, Any], strategies: Mapping[str, Any] | None) -> dict[str, str]:
    return {
        "model_card_early_warning.md": early_warning_card(metrics),
        "model_card_segment.md": segment_card(metrics),
        "model_card_uplift.md": uplift_card(metrics, strategies),
    }
