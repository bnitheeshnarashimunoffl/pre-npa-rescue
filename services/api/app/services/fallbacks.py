"""Fallback providers used while the real WS2/WS3/WS4 packages are not available.

Each is reported as ``"fixture"`` by ``GET /health`` and logs a warning at startup (B4: the
demo must never crash because one piece is missing). They never invent relief: options come
only from ``contracts/fixtures`` (generated by WS3's policy engine).
"""

import json
import uuid
from collections.abc import Iterator
from datetime import UTC, datetime, timedelta
from pathlib import Path
from typing import Any, ClassVar
from zoneinfo import ZoneInfo

from sqlalchemy import select
from sqlalchemy.orm import Session, sessionmaker

from app import orm
from npa_contracts.constants import BUSINESS_TZ, CONTACT_WINDOW
from npa_contracts.enums import Actor, Channel, Lang, OfferStatus
from npa_contracts.models import (
    Affordability,
    BotReply,
    ChatTurnRequest,
    ComplianceDecision,
    GrievanceOfficer,
    NextBestAction,
    Offer,
    ReasonCode,
    ReliefOption,
    RiskScore,
    SegmentResult,
    UpliftResult,
)

OFFER_VALIDITY = timedelta(days=7)


def _load(contracts_dir: Path, name: str) -> Any:
    return json.loads((contracts_dir / "fixtures" / name).read_text(encoding="utf-8"))


class ScoresRiskProvider:
    """``RiskProvider`` over the ``scores`` table (seeded from WS2's scores.parquet or the
    fixtures). Raises ``KeyError`` for an unscored account."""

    def __init__(self, sessions: sessionmaker[Session]) -> None:
        self._sessions = sessions

    def _row(self, account_id: str, as_of_month: str) -> orm.Score:
        with self._sessions() as s:
            row = s.get(orm.Score, (account_id, as_of_month))
        if row is None:
            raise KeyError(account_id)
        return row

    def risk(self, account_id: str, as_of_month: str) -> RiskScore:
        r = self._row(account_id, as_of_month)
        return RiskScore(
            account_id=account_id,
            as_of_month=as_of_month,
            p_roll_forward=r.p_roll_forward,
            risk_band=r.risk_band,
            reasons=[ReasonCode.model_validate(x) for x in r.reasons],
            model_version=r.risk_model_version,
        )

    def segment(self, account_id: str, as_of_month: str) -> SegmentResult:
        r = self._row(account_id, as_of_month)
        return SegmentResult(
            account_id=account_id,
            segment=r.segment,
            confidence=r.segment_confidence,
            model_version=r.segment_model_version,
        )

    def uplift(self, account_id: str, as_of_month: str) -> UpliftResult:
        r = self._row(account_id, as_of_month)
        return UpliftResult(
            account_id=account_id,
            uplift_score=r.uplift_score,
            uplift_group=r.uplift_group,
            recommended_treatment=r.recommended_treatment,
            model_version=r.uplift_model_version,
        )

    def score_batch(
        self, as_of_month: str
    ) -> Iterator[tuple[RiskScore, SegmentResult, UpliftResult]]:
        with self._sessions() as s:
            ids = list(
                s.scalars(select(orm.Score.account_id).where(orm.Score.as_of_month == as_of_month))
            )
        for account_id in ids:
            yield (
                self.risk(account_id, as_of_month),
                self.segment(account_id, as_of_month),
                self.uplift(account_id, as_of_month),
            )


class CachedNBAProvider:
    """``NBAProvider`` over the ``nba`` table (the per-month cache the collector queue reads)."""

    def __init__(self, sessions: sessionmaker[Session]) -> None:
        self._sessions = sessions

    def next_best_action(self, account_id: str, as_of_month: str) -> NextBestAction:
        with self._sessions() as s:
            row = s.get(orm.NBA, (account_id, as_of_month))
        if row is None:
            raise KeyError(account_id)
        return NextBestAction.model_validate(row.payload)


class FixturePolicyProvider:
    """``PolicyProvider`` serving WS3-generated fixture options for the demo customers only.

    ``propose_offer`` only accepts an option the customer was offered (AI proposes, rules
    decide); options that need no human approval are approved by ``policy_engine``, as WS3's
    engine does.
    """

    _FILES: ClassVar[dict[str, str]] = {
        "CUST-DEMO-PRIYA": "relief_options_priya.json",
        "CUST-DEMO-RAVI": "relief_options_ravi.json",
    }

    def __init__(self, contracts_dir: Path, *, clock: Any = None) -> None:
        self._dir = contracts_dir
        self._clock = clock or (lambda: datetime.now(UTC))
        self._grievance = GrievanceOfficer.model_validate(
            _load(contracts_dir, "complaint.json")["grievance_officer"]
        )

    def relief_options(self, customer_id: str, affordability: Affordability) -> list[ReliefOption]:
        name = self._FILES.get(customer_id)
        if name is None:
            return []
        return [ReliefOption.model_validate(o) for o in _load(self._dir, name)]

    def propose_offer(self, customer_id: str, option_id: str, actor: Actor) -> Offer:
        options = {o.option_id: o for o in self.relief_options(customer_id, _NO_AFFORDABILITY)}
        option = options.get(option_id)
        if option is None:
            raise KeyError(option_id)
        now = self._clock()
        auto = not option.requires_human_approval
        return Offer(
            offer_id=f"OFFER-{uuid.uuid4()}",
            customer_id=customer_id,
            account_id=customer_id.replace("CUST-", "ACC-", 1),
            option=option,
            status=OfferStatus.APPROVED if auto else OfferStatus.PROPOSED,
            proposed_by=actor,
            approved_by="policy_engine" if auto else None,
            created_at=now,
            expires_at=now + OFFER_VALIDITY,
        )

    def grievance_officer(self) -> GrievanceOfficer:
        return self._grievance


_NO_AFFORDABILITY = Affordability(
    customer_id="",
    declared_income_paise=None,
    declared_expenses_paise=None,
    dependants=None,
    max_monthly_payment_paise=0,
    source="estimated",
)


class WindowComplianceProvider:
    """Minimal ``ComplianceProvider``: only the 08:00-19:00 IST contact window (RBI RBC
    Directions para 454Y(4)). WS3's ``ComplianceGuard`` adds frequency, quiet times,
    do-not-contact flags and the harsh-language filter."""

    RULE = "RBI-454Y4-WINDOW"

    def __init__(self, tz: str = BUSINESS_TZ) -> None:
        self._tz = ZoneInfo(tz)

    def check_contact(
        self, customer_id: str, channel: Channel, at: datetime, actor: Actor
    ) -> ComplianceDecision:
        local = at.astimezone(self._tz)
        start, end = CONTACT_WINDOW
        if start <= local.time() < end:
            return ComplianceDecision(
                allowed=True,
                rule_ids=[self.RULE],
                next_allowed_at=None,
                explanation="Inside the 08:00-19:00 IST contact window.",
            )
        nxt = local.replace(hour=start.hour, minute=0, second=0, microsecond=0)
        if local.time() >= end:
            nxt += timedelta(days=1)
        return ComplianceDecision(
            allowed=False,
            rule_ids=[self.RULE],
            next_allowed_at=nxt.astimezone(UTC),
            explanation="Outside the 08:00-19:00 IST contact window (RBI RBC para 454Y(4)).",
        )

    def check_text(self, text: str, lang: Lang) -> ComplianceDecision:
        return ComplianceDecision(
            allowed=True,
            rule_ids=[],
            next_allowed_at=None,
            explanation="Fallback: language checks need npa_rules (WS3).",
        )


class FixtureChatEngine:
    """Stand-in for WS4's ``ChatEngine``: replays the zero-capacity reply for Ravi and the
    plan-offer reply for everyone else, with the caller's session id."""

    def __init__(self, contracts_dir: Path) -> None:
        self._offer = BotReply.model_validate(_load(contracts_dir, "bot_reply_offer.json"))
        self._zero = BotReply.model_validate(_load(contracts_dir, "bot_reply_zero_capacity.json"))

    def handle(self, session_id: str, customer_id: str, req: ChatTurnRequest) -> BotReply:
        reply = self._zero if customer_id == "CUST-DEMO-RAVI" else self._offer
        return reply.model_copy(update={"session_id": session_id})
